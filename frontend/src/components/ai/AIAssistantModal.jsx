import React, { useState } from "react";
import Modal from "../ui/Modal";
import Button from "../ui/Button";
import Badge from "../ui/Badge";
import {
  simplifyInstructionsWithAI,
  draftDoctorQuestionWithAI,
  summarizeConsultationWithAI,
} from "../../api";

const AIAssistantModal = ({ isOpen, onClose }) => {
  const [mode, setMode] = useState("simplify"); // 'simplify' | 'draft_question' | 'summarize'
  const [loading, setLoading] = useState(false);
  const [result, setResult] = useState(null);

  // Form states
  const [medInput, setMedInput] = useState("Atorvastatin 20mg - 1 Tab OD Nocte post cibus");
  const [symptomInput, setSymptomInput] = useState("mild dizziness when standing up in the morning");
  const [doctorNameInput, setDoctorNameInput] = useState("Dr. Sarah Jenkins");

  const handleRunAI = async () => {
    try {
      setLoading(true);
      setResult(null);

      let data;
      if (mode === "simplify") {
        data = await simplifyInstructionsWithAI({
          medicines: [{ name: "Prescribed Regimen", instructions: medInput }],
          diagnosis: "General Wellness & Lipid Regulation",
        });
      } else if (mode === "draft_question") {
        data = await draftDoctorQuestionWithAI({
          symptomTopic: symptomInput,
          currentMedication: "Prescribed Routine",
          duration: "the past few days",
        });
      } else {
        data = await summarizeConsultationWithAI({
          doctorName: doctorNameInput,
          notes: "Routine follow-up regarding blood pressure and lipid profile adherence.",
        });
      }

      if (data && data.success) {
        setResult(data);
      }
    } catch (e) {
      console.error("AI assistant error:", e);
    } finally {
      setLoading(false);
    }
  };

  return (
    <Modal isOpen={isOpen} onClose={onClose} title="TriMedi AI Healthcare Assistant" maxWidth="max-w-xl">
      <div className="space-y-4">
        {/* Assistive Warning Banner */}
        <div className="p-3 bg-teal-50/60 dark:bg-teal-950/30 border border-teal-200 dark:border-teal-800/60 rounded-xl text-[11px] text-teal-800 dark:text-teal-300 flex items-start gap-2">
          <span className="text-base flex-shrink-0">✨</span>
          <div>
            <strong>AI-Assisted Guidance:</strong> This information is generated by AI for assistive communication purposes and is not a medical diagnosis. Doctor-authorized clinical information remains authoritative.
          </div>
        </div>

        {/* Mode Selector */}
        <div className="grid grid-cols-3 gap-2">
          <button
            onClick={() => {
              setMode("simplify");
              setResult(null);
            }}
            className={`p-2.5 rounded-xl border text-xs font-semibold text-center transition ${
              mode === "simplify"
                ? "bg-teal-500 text-white border-teal-500 shadow-sm"
                : "bg-slate-50 dark:bg-slate-800/50 border-slate-200 dark:border-slate-700 text-slate-700 dark:text-slate-300"
            }`}
          >
            💊 Simplify Dosage
          </button>
          <button
            onClick={() => {
              setMode("draft_question");
              setResult(null);
            }}
            className={`p-2.5 rounded-xl border text-xs font-semibold text-center transition ${
              mode === "draft_question"
                ? "bg-teal-500 text-white border-teal-500 shadow-sm"
                : "bg-slate-50 dark:bg-slate-800/50 border-slate-200 dark:border-slate-700 text-slate-700 dark:text-slate-300"
            }`}
          >
            ❓ Draft Doctor Query
          </button>
          <button
            onClick={() => {
              setMode("summarize");
              setResult(null);
            }}
            className={`p-2.5 rounded-xl border text-xs font-semibold text-center transition ${
              mode === "summarize"
                ? "bg-teal-500 text-white border-teal-500 shadow-sm"
                : "bg-slate-50 dark:bg-slate-800/50 border-slate-200 dark:border-slate-700 text-slate-700 dark:text-slate-300"
            }`}
          >
            📋 Consultation Summary
          </button>
        </div>

        {/* Inputs based on Mode */}
        {mode === "simplify" && (
          <div className="space-y-1">
            <label className="text-xs font-bold text-slate-700 dark:text-slate-300">
              Prescription Instructions / Latin Terms:
            </label>
            <textarea
              rows={2}
              value={medInput}
              onChange={(e) => setMedInput(e.target.value)}
              className="w-full text-xs p-2.5 rounded-xl border border-slate-200 dark:border-slate-700 bg-slate-50 dark:bg-slate-800 text-slate-900 dark:text-slate-100 focus:outline-none focus:ring-1 focus:ring-teal-500"
              placeholder="Enter prescription instructions..."
            />
          </div>
        )}

        {mode === "draft_question" && (
          <div className="space-y-1">
            <label className="text-xs font-bold text-slate-700 dark:text-slate-300">
              What symptoms or questions would you like to ask your doctor?
            </label>
            <textarea
              rows={2}
              value={symptomInput}
              onChange={(e) => setSymptomInput(e.target.value)}
              className="w-full text-xs p-2.5 rounded-xl border border-slate-200 dark:border-slate-700 bg-slate-50 dark:bg-slate-800 text-slate-900 dark:text-slate-100 focus:outline-none focus:ring-1 focus:ring-teal-500"
              placeholder="e.g. Mild stomach discomfort after taking morning tablets..."
            />
          </div>
        )}

        {mode === "summarize" && (
          <div className="space-y-1">
            <label className="text-xs font-bold text-slate-700 dark:text-slate-300">
              Doctor / Clinic Name:
            </label>
            <input
              type="text"
              value={doctorNameInput}
              onChange={(e) => setDoctorNameInput(e.target.value)}
              className="w-full text-xs p-2.5 rounded-xl border border-slate-200 dark:border-slate-700 bg-slate-50 dark:bg-slate-800 text-slate-900 dark:text-slate-100 focus:outline-none focus:ring-1 focus:ring-teal-500"
            />
          </div>
        )}

        {/* Action Button */}
        <Button variant="primary" size="md" className="w-full" onClick={handleRunAI} disabled={loading}>
          {loading ? "Processing with AI Clinical Pipeline..." : "Generate AI Assistance ✨"}
        </Button>

        {/* Results Container */}
        {result && (
          <div className="p-4 bg-slate-50 dark:bg-slate-800/70 border border-slate-200 dark:border-slate-700 rounded-xl space-y-2.5">
            <div className="flex items-center justify-between">
              <Badge variant="primary" size="sm">
                {result.label || "AI-assisted summary"}
              </Badge>
              <span className="text-[10px] text-slate-400">Deterministic Clinical NLP</span>
            </div>

            {result.guidelines && (
              <div className="space-y-2">
                <p className="text-xs font-medium text-slate-700 dark:text-slate-300">{result.summary}</p>
                {result.guidelines.map((g, i) => (
                  <div key={i} className="p-2.5 bg-white dark:bg-slate-900 rounded-lg text-xs space-y-1 border border-slate-100 dark:border-slate-800">
                    <p className="font-bold text-teal-600 dark:text-teal-400">💡 {g.guideline}</p>
                    <p className="text-[11px] text-slate-400">⚠️ {g.precautions}</p>
                  </div>
                ))}
              </div>
            )}

            {result.draftedQuestion && (
              <div className="p-3 bg-white dark:bg-slate-900 rounded-lg border border-teal-200 dark:border-teal-800/60">
                <p className="text-xs text-slate-800 dark:text-slate-200 leading-relaxed font-medium">
                  "{result.draftedQuestion}"
                </p>
                {result.tips && (
                  <ul className="mt-2 text-[10px] text-slate-400 list-disc list-inside space-y-0.5">
                    {result.tips.map((t, idx) => (
                      <li key={idx}>{t}</li>
                    ))}
                  </ul>
                )}
              </div>
            )}

            {result.actionItems && (
              <div className="space-y-1 text-xs">
                <p className="font-bold text-slate-700 dark:text-slate-300">{result.summary}</p>
                <ul className="list-disc list-inside space-y-1 text-slate-600 dark:text-slate-400">
                  {result.actionItems.map((item, i) => (
                    <li key={i}>{item}</li>
                  ))}
                </ul>
              </div>
            )}
          </div>
        )}
      </div>
    </Modal>
  );
};

export default AIAssistantModal;
